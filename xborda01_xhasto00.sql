-- Generalization/Specialization - Customers, Individuals, Companies
-- Implemented by adding foreign key into Individuals/Companies table
-- that references customer in Customers table
CREATE TABLE Customers (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(100) NOT NULL,
    phone_number VARCHAR(20) NOT NULL
);

CREATE SEQUENCE Var_Symbol
START WITH 1000000
MAXVALUE 9999999
NOCYCLE;

CREATE TABLE Individuals (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Variable_symbol INT DEFAULT Var_Symbol.NEXTVAL,
    Customer_id INT NOT NULL,
    CONSTRAINT individuals_customer
		FOREIGN KEY (Customer_id) REFERENCES Customers (ID)
		ON DELETE CASCADE,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL
);

CREATE TABLE Companies (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Customer_id INT NOT NULL,
    CONSTRAINT companies_customer
		FOREIGN KEY (Customer_id) REFERENCES Customers (ID)
		ON DELETE CASCADE,
    IC VARCHAR(10) UNIQUE NOT NULL CHECK (REGEXP_LIKE(IC,'[0-9]{8}')),
    DIC VARCHAR(12) UNIQUE NOT NULL CHECK (REGEXP_LIKE(DIC,'[A-Z]{2}[0-9]{9,10}'))
);

CREATE TABLE Vehicles (
    VIN VARCHAR(17) PRIMARY KEY,
    customer_ID NUMBER NOT NULL,
    FOREIGN KEY (customer_ID) REFERENCES Customers(ID),
    customer_tag VARCHAR(50)
);

CREATE TABLE Workplace (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name" VARCHAR(100) NOT NULL 
);

-- Generalization/Specialization - Employees, Technician, Manager
-- Implemented by adding foreign key into Technician/Manager/Mechanic table
-- that references employee in Employees table
CREATE TABLE Employees (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name VARCHAR(50) NOT NULL,
    last_name VARCHAR(50) NOT NULL,
    email VARCHAR(100) NOT NULL,
    phone_number VARCHAR(20) NOT NULL,
    workplace_ID NUMBER,
    FOREIGN KEY (workplace_ID) REFERENCES Workplace(ID)
);

CREATE TABLE Orders (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "state" INT NOT NULL,
    start_date DATE NOT NULL,
    expected_finish_date DATE,
    price INT,
    billable_time INT,
    "description" VARCHAR(30),
    vehicle_ID VARCHAR(17),
    customer_ID INT,
    technician_ID INT,
    FOREIGN KEY (vehicle_ID) REFERENCES Vehicles(VIN),
    FOREIGN KEY (customer_ID) REFERENCES Customers(ID),
    FOREIGN KEY (technician_ID) REFERENCES Employees(ID)
);

CREATE TABLE Calendar_Items (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_ID INT,
    FOREIGN KEY (order_ID) REFERENCES Orders(ID),
    "date" DATE NOT NULL, 
    "start_time" TIMESTAMP NOT NULL, 
    "end_time" TIMESTAMP NOT NULL, 
    is_assigned INT DEFAULT 0,
    "type" INT NOT NULL, 
    created_by_ID INT,
    FOREIGN KEY (created_by_ID) REFERENCES Employees(ID),
    workplace_ID INT,
    FOREIGN KEY (workplace_ID) REFERENCES Workplace(ID),
    mechanic_ID INT,
    FOREIGN KEY (mechanic_ID) REFERENCES Employees(ID)
);

CREATE TABLE Services (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    price INT NOT NULL,
    expected_time INT NOT NULL,
    needed_specialisation VARCHAR(50) NOT NULL,
    "type" INT CHECK ("type" IN (0,1)) 
);

CREATE TABLE Services_on_order(
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INT NOT NULL,
    FOREIGN KEY (order_id) REFERENCES Orders (ID),
    service_id INT NOT NULL,
    FOREIGN KEY (service_id) REFERENCES Services (ID),
    quantity INT NOT NULL
);

CREATE TABLE Store_Items (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_address VARCHAR(10) NOT NULL,
    "name" VARCHAR(30) NOT NULL,
    quantity INT NOT NULL,
    price INT NOT NULL
);

CREATE TABLE Items_on_order(
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id INT NOT NULL,
    FOREIGN KEY (order_id) REFERENCES Orders (ID),
    item_id INT NOT NULL,
    FOREIGN KEY (item_id) REFERENCES Store_Items (ID),
    quantity INT NOT NULL
);

CREATE TABLE Technician (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Employee_id INT NOT NULL,
    CONSTRAINT technician_employees
		FOREIGN KEY (Employee_id) REFERENCES Employees (ID)
		ON DELETE CASCADE,
    work_focus INT CHECK (work_focus IN (0,1))
);

CREATE TABLE Training_Programs (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "name" VARCHAR(100) NOT NULL
);

CREATE TABLE Mechanic (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Employee_id INT NOT NULL,
    CONSTRAINT mechanic_employees
		FOREIGN KEY (Employee_id) REFERENCES Employees (ID)
		ON DELETE CASCADE
);

CREATE TABLE Mechanic_Has_Program(
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    program_id INT NOT NULL,
    FOREIGN KEY (program_id) REFERENCES Training_Programs (ID),
    mechanic_id INT NOT NULL,
    FOREIGN KEY (mechanic_id) REFERENCES Mechanic (ID)
);

CREATE TABLE Manager (
    ID INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    Employee_id INT NOT NULL,
    CONSTRAINT manager_employees
		FOREIGN KEY (Employee_id) REFERENCES Employees (ID)
		ON DELETE CASCADE
);

