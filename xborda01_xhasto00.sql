-- TRIGGER 1
    CREATE OR REPLACE TRIGGER insert_to_items_on_order_update_order_update_store_items
    AFTER INSERT ON Items_on_order
    FOR EACH ROW
    DECLARE
        item_price INTEGER;
    BEGIN
        -- substract used quantity of item from item's quantity
        UPDATE Store_items
        SET quantity = quantity - :NEW.quantity
        WHERE ID = :NEW.item_id;

        -- get price of the item
        SELECT price INTO item_price
        FROM Store_items
        WHERE ID = :NEW.item_id;

        -- add the price of added item * quantity to order price
        UPDATE Orders
        SET price = price + (item_price * :NEW.quantity)
        WHERE ID = :NEW.order_id; 
    END;
    /

    -- before first trigger
    SELECT * FROM Orders WHERE ID = 1;
    SELECT * FROM Store_Items WHERE ID = 2;

    -- add used item in some quantity to order (Items_on_order)
    INSERT INTO Items_on_order (item_id, order_id, quantity) VALUES (2, 1, 4);

    -- after first trigger
    SELECT * FROM Orders WHERE ID = 1;
    SELECT * FROM Store_Items WHERE ID = 2;

-- TRIGGER 2
    CREATE OR REPLACE TRIGGER insert_to_services_on_order_update_order
    AFTER INSERT ON Services_on_order
    FOR EACH ROW
    DECLARE
        service_expected_time INTEGER;
        service_price INTEGER;
    BEGIN
        -- get expected_time and price from Service (on that exact service used)
        SELECT expected_time, price 
        INTO service_expected_time, service_price
        FROM Services
        WHERE ID = :NEW.service_id;

        -- update billable time and price on order with added service (in some not null quantity)
        UPDATE Orders
        SET 
        billable_time = billable_time + service_expected_time,
        price = price + (service_price * :NEW.quantity)
        WHERE ID = :NEW.order_id;
    END;
    /

    -- before second trigger
    SELECT * FROM Orders WHERE ID = 1;
    SELECT * FROM Services WHERE ID = 1;

